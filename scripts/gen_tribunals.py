#!/usr/bin/env python3
"""Regenerate src/tribunals_gen.rs from the official DATAJUD wiki catalog.

Fetches https://datajud-wiki.cnj.jus.br/api-publica/endpoints, parses the
91 tribunal rows (alias, official name, justice segment) and emits the Rust
static catalog. Run from the repository root:

    python3 scripts/gen_tribunals.py
"""

import html.parser
import re
import sys
import urllib.request

WIKI_URL = "https://datajud-wiki.cnj.jus.br/api-publica/endpoints"
OUT = "src/tribunals_gen.rs"

CATS = [
    "Tribunais Superiores",
    "Justiça Federal",
    "Justiça Estadual",
    "Justiça do Trabalho",
    "Justiça Eleitoral",
    "Justiça Militar",
]
SEG = {
    "Tribunais Superiores": "Superior",
    "Justiça Federal": "Federal",
    "Justiça Estadual": "State",
    "Justiça do Trabalho": "Labor",
    "Justiça Eleitoral": "Electoral",
    "Justiça Militar": "Military",
}
# Cosmetic name fixes (aliases stay byte-exact as documented).
FIX = {
    "tre-ba": "Tribunal Regional Eleitoral da Bahia",
    "tjms": "Tribunal de Justiça de Mato Grosso do Sul",
    "tre-ms": "Tribunal Regional Eleitoral de Mato Grosso do Sul",
    "tjmmg": "Tribunal de Justiça Militar de Minas Gerais",
    "tjmrs": "Tribunal de Justiça Militar do Rio Grande do Sul",
    "tjmsp": "Tribunal de Justiça Militar de São Paulo",
}


class TextExtractor(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.parts = []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style"):
            self.skip += 1
        if tag in ("p", "div", "li", "tr", "br", "h1", "h2", "h3", "h4"):
            self.parts.append("\n")

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip -= 1

    def handle_data(self, data):
        if not self.skip:
            self.parts.append(data)


def main():
    print(f"fetching {WIKI_URL} ...")
    req = urllib.request.Request(WIKI_URL, headers={"User-Agent": "datajud-mcp-gen/1.0"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        page = resp.read().decode("utf-8")

    extractor = TextExtractor()
    extractor.feed(page)
    text = "".join(extractor.parts)

    rows, cat = [], None
    for line in text.splitlines():
        line = line.strip()
        for c in CATS:
            if line == c or line.endswith(":" + c):
                cat = c
        m = re.search(r"api_publica_([a-z0-9\-]+)/_search", line)
        if m and cat:
            alias = m.group(1)
            # The cell is "Namehttps://.../_search" (or "Name [url]") — keep just the name.
            raw_name = re.split(r"https?://|\[", line)[0].strip()
            name = FIX.get(alias, raw_name)
            rows.append((alias, name, SEG[cat]))

    if len(rows) != 91:
        sys.exit(f"expected 91 tribunals, parsed {len(rows)} — has the wiki changed?")
    seen = set()
    for alias, _, _ in rows:
        if alias in seen:
            sys.exit(f"duplicate alias {alias}")
        seen.add(alias)

    out = [
        "// Generated by scripts/gen_tribunals.py from the official DATAJUD wiki catalog.",
        "// Source: https://datajud-wiki.cnj.jus.br/api-publica/endpoints",
        "",
        "/// The full catalog of the 91 tribunals of the DATAJUD public API.",
        "pub static TRIBUNALS: &[Tribunal] = &[",
    ]
    for alias, name, seg in rows:
        esc = name.replace("\\", "\\\\").replace('"', '\\"')
        out.append(
            f'    Tribunal {{ alias: "{alias}", name: "{esc}", segment: Segment::{seg} }},'
        )
    out.append("];")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT} with {len(rows)} tribunals")


if __name__ == "__main__":
    main()
